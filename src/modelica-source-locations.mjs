/** Resolve an authored component name or its old flat-directory identity. */
export function modelicaSourcePath(name){
  if(typeof name!=='string')throw new Error('Expected a Modelica source name');
  const key=/^models\/([A-Za-z_]\w*)\.mo$/.exec(name)?.[1]??name;
  if(!Object.hasOwn(modelicaSourceLocations,key))
    throw new Error('Unknown Modelica source: '+name);
  return modelicaSourceLocations[key];
}

/** Migrate saved path keys only. Authored source text is never replaced. */
export function migrateModelicaSourcePath(path){
  const key=/^models\/([A-Za-z_]\w*)\.mo$/.exec(path)?.[1];
  return key&&Object.hasOwn(modelicaSourceLocations,key)?modelicaSourceLocations[key]:path;
}
